#!/usr/bin/env python
"""Write the six synthetic probe signals used by the offline demo path.

Two seconds of shaped noise each, a few kilobytes, so the decode, prosody and
plotting paths can be exercised without any dataset.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from _fixtures import write_tone  # noqa: E402

OUT_DIR = ROOT / "demo_samples" / "probes"

# Six profiles spanning the prosodic space the stress composite actually reads:
# quiet and slow, bright and fast, wide pitch range, flat monotone, and so on.
PROFILES: list[dict[str, object]] = [
    {"name": "synthetic_calm_slow", "f0": 96.0, "vibrato_hz": 0.45, "syllable_hz": 2.4,
     "noise": 0.003, "seed": 11,
     "note": "low pitch, slow syllables, quiet floor - reads as low arousal"},
    {"name": "synthetic_bright_fast", "f0": 168.0, "vibrato_hz": 1.10, "syllable_hz": 4.6,
     "noise": 0.004, "seed": 12,
     "note": "high pitch, fast syllables - reads as high arousal"},
    {"name": "synthetic_wide_range", "f0": 132.0, "vibrato_hz": 2.20, "syllable_hz": 3.4,
     "noise": 0.005, "seed": 13,
     "note": "wide pitch excursion - exercises the f0 spread features"},
    {"name": "synthetic_monotone", "f0": 112.0, "vibrato_hz": 0.05, "syllable_hz": 3.0,
     "noise": 0.003, "seed": 14,
     "note": "near-flat intonation - the classic low-variability case"},
    {"name": "synthetic_noisy_room", "f0": 124.0, "vibrato_hz": 0.80, "syllable_hz": 3.2,
     "noise": 0.030, "seed": 15,
     "note": "raised noise floor - exercises the SNR estimate"},
    {"name": "synthetic_halting", "f0": 140.0, "vibrato_hz": 1.60, "syllable_hz": 1.8,
     "noise": 0.004, "seed": 16,
     "note": "sparse syllables with long gaps - exercises pause ratio"},
]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--force", action="store_true", help="overwrite existing files")
    parser.add_argument("--out", default=str(OUT_DIR))
    args = parser.parse_args(argv)

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    written: list[dict[str, object]] = []
    for profile in PROFILES:
        target = out_dir / f"{profile['name']}.wav"
        if target.exists() and not args.force:
            print(f"  skip {target.name} (exists; use --force)")
        else:
            write_tone(
                target,
                seconds=2.0,
                f0=float(profile["f0"]),
                vibrato_hz=float(profile["vibrato_hz"]),
                syllable_hz=float(profile["syllable_hz"]),
                noise=float(profile["noise"]),
                seed=int(profile["seed"]),
            )
            print(f"  wrote {target.name} ({target.stat().st_size / 1024:.0f} KB)")
        written.append(
            {
                "file": target.name,
                "kind": "synthetic",
                "seconds": 2.0,
                "sample_rate": 16000,
                "description": profile["note"],
                "provenance": "generated by scripts/prepare_demo_samples.py; not speech, not from any dataset",
            }
        )

    manifest = out_dir / "PROVENANCE.json"
    payload = {
        "warning": (
            "These are synthesised test signals, not recordings and not speech. They exist to "
            "exercise the audio, prosody and plotting paths without bundling a dataset. Any "
            "interpretation shown for them in the interface is meaningless by construction."
        ),
        "dataset_reference": {
            "name": "RAVDESS",
            "doi": "10.5281/zenodo.1188976",
            "licence": "CC BY-NC-SA 4.0",
            "fetch": "python scripts/fetch_ravdess.py --from-zip <Audio_Speech_Actors_01-24.zip>",
        },
        "clips": written,
    }
    manifest.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"\nwrote {manifest}")
    print(f"{len(written)} clips in {out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
